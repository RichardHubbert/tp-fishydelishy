#!/usr/bin/env node

/**
 * Interactive setup script for creating a new client configuration
 * 
 * Usage: npm run new-client
 * 
 * This script will:
 * 1. Prompt for all essential client information
 * 2. Generate a new src/config/site.ts file with those values
 * 3. Create a basic .env file with placeholders
 */

import * as readline from 'readline';
import * as fs from 'fs';
import * as path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const rl = readline.createInterface({
  input: process.stdin,
  output: process.stdout
});

function question(query) {
  return new Promise(resolve => rl.question(query, resolve));
}

async function main() {
  console.log('\n🎉 Welcome to Table Pilot Client Setup!\n');
  console.log('This wizard will help you configure a new client site.\n');
  console.log('Press Ctrl+C at any time to cancel.\n');

  try {
    // Collect information
    const businessName = await question('Business name: ');
    const logoText = await question('Logo badge text (2-3 chars, e.g., "TP"): ');
    const primaryColor = await question('Primary brand color (amber, blue, green, purple, etc.): ');
    const phone = await question('Phone number (optional): ');
    const email = await question('Email address (optional): ');
    const address = await question('Physical address (optional): ');
    const openingHours = await question('Opening hours (e.g., "Daily: 11:00 AM - 10:00 PM"): ');
    const lastBooking = await question('Last booking time (e.g., "7:30 PM"): ');
    const domain = await question('Domain (e.g., "yoursite.com"): ');
    const basePath = await question('Base path (e.g., "/businessname" or "/" for root): ');
    const twitterHandle = await question('Twitter handle (optional, e.g., "@yourbusiness"): ');

    // Generate configuration
    const config = generateConfig({
      businessName,
      logoText,
      primaryColor,
      phone,
      email,
      address,
      openingHours,
      lastBooking,
      domain,
      basePath,
      twitterHandle
    });

    // Write to file
    const configPath = path.join(__dirname, 'src', 'config', 'site.ts');
    fs.writeFileSync(configPath, config, 'utf8');
    console.log('\n✅ Configuration written to src/config/site.ts');

    // Create .env if it doesn't exist
    const envPath = path.join(__dirname, '.env');
    if (!fs.existsSync(envPath)) {
      const envContent = `# Copy from your Supabase project settings
VITE_SUPABASE_URL=https://your-project.supabase.co
VITE_SUPABASE_ANON_KEY=your-anon-key-here
`;
      fs.writeFileSync(envPath, envContent, 'utf8');
      console.log('✅ Created .env file (update with your Supabase credentials)');
    }

    console.log('\n📝 Next steps:');
    console.log('   1. Replace assets in public/brand/');
    console.log('   2. Update .env with your Supabase credentials');
    console.log('   3. Run: npm install');
    console.log('   4. Run: npm run dev');
    console.log('   5. See CLONING.md for complete setup instructions\n');

  } catch (error) {
    console.error('\n❌ Error:', error.message);
  } finally {
    rl.close();
  }
}

